/**
 * 开屏动画的「就绪信号」（2026-10-17 站长要求）。
 *
 * 背景：`index.html` 里那段开屏（云朵描边 + 站名）原来是**纯 CSS 定时**的 ——
 * 0.72s 画完、1.32s 收尾、1.5s 把元素从 DOM 摘掉，跟「应用到底准备好没有」毫无关系。
 * 于是 JS 慢一点就会出现「云画完了，界面还只有背景」；而反过来提前撤掉又会露出
 * 半成品界面 —— 两头都不对。
 *
 * 现在的契约：
 *   · 开屏里的云朵画到 **差一点闭合** 就停下等；
 *   · 本文件所在的 `BootReadyProbe` 在「认证就绪 + 当前路由内容已经画到屏幕上」时
 *     调 `signalBootReady()`；
 *   · 开屏收到信号才把最后那一小段接上（闭合），然后整块淡出。
 *
 * 为什么信号要放在 `window` 上、由内联脚本提供：
 *   开屏必须能在**任何 JS 都还没跑**的时候就正确显示，所以它不能是 React 组件；
 *   反过来它又要被 React 侧通知，于是只能走这个最小的全局钩子。
 *   钩子缺席（单测环境、被 CSP 拦掉）时这里静默忽略 —— 开屏自己还有兜底超时。
 */
declare global {
  interface Window {
    /** 由 `index.html` 的内联脚本提供：合拢云朵并淡出开屏 */
    __bootReady?: () => void
  }
}

let signaled = false

/**
 * 通知开屏：应用已经准备好，可以收尾了。幂等（重复调用无副作用）。
 *
 * ⚠️ 只在「用户真正看到内容」时调用。提前调用等于用一个漂亮的动画
 *    盖住一个还没准备好的界面 —— 那比现在更糟。
 */
export function signalBootReady(): void {
  if (signaled) return
  signaled = true
  try {
    window.__bootReady?.()
  } catch {
    // 开屏脚本缺席或抛错都不该影响应用本身
  }
}
