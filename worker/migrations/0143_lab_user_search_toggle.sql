-- 0143_lab_user_search_toggle.sql
-- AI 实验室：**用户级的「启用联网搜索」开关**（2026-10-10 站长要求）。
--
-- 背景：站点 key 是「谁用谁扣积分」的。但很多人根本不需要联网搜索 ——
-- 模型在做别的事时顺手搜一下，用户就莫名其妙被扣分了。
-- 所以给每个人一个显式开关：**默认关闭**，想用的人自己去打开。
--
-- ⚠️ 默认值必须是 0（关）。站长明确说「默认关闭」——
--    联网搜索是**会花钱**的动作，默认开的后果是所有人都被扣分而不自知。
--    默认关 = 不打开就完全不受影响。
--
-- 开关的效力在两处：
--   1. 前端拼系统提示时**根本不把 <lab_web_search> 告诉模型**（它不会去试）；
--   2. 后端 `/api/lab/web-search` 再拦一道（前端可以被绕过，钱是真扣的）。
-- 只做 1 是「君子协定」，必须两边都做。

ALTER TABLE lab_user_settings ADD COLUMN web_search_enabled INTEGER NOT NULL DEFAULT 0;
