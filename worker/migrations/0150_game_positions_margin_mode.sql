-- 0150_game_positions_margin_mode.sql
-- 造物典藏「在线投资」：仓位合并（均价）+ 逐仓/全仓两种保证金模式。
--
-- 站长要求（2026-10-11）：
--   1. 「现在可以开多个仓位并且仓位之间价格独立，改为算平均价」
--      ⇒ 同一人、同一方向、**同一保证金模式**只保留**一行**在仓：
--        再加仓就把 size/margin 累加、开仓价按**规模加权**取平均。
--   2. 「添加全仓和逐仓保证金两种模式」
--      ⇒ 逐仓：亏损上限 = 该仓保证金（现状，穿价即强平）；
--         全仓：该仓与账户可用余额共同担保，账户权益 < 维持保证金才强平，
--               亏损可以超过该仓保证金（由余额补足）。
--
-- 为什么模式要参与合并键：逐仓与全仓的**强平价与风险完全不同**，
-- 混在一行里就没法算了 —— 两个模式各自独立一行、各自独立强平，互不牵连。
--
-- ⚠️ 存量仓位：默认 'isolated'（老仓本来就是逐仓口径），
--    所以这个迁移不会改变任何现有仓位的风险特征。
--    存量里同一人同方向可能有多行（老行为），代码会在下次加仓时
--    自动把它们合并成一行（并把它们的开仓流水挂到合并后的仓位上）。
ALTER TABLE game_positions ADD COLUMN margin_mode TEXT NOT NULL DEFAULT 'isolated';

-- 加仓时要按 (用户, 方向, 模式, 在仓) 找现有仓位 —— 这个索引就是那个查询的支撑。
CREATE INDEX IF NOT EXISTS idx_game_positions_bucket
  ON game_positions(user_id, side, margin_mode, status);
