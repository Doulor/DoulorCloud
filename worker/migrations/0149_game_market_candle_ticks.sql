-- 0149_game_market_candle_ticks.sql
-- 造物典藏「在线投资」：给行情行加「当前 K 线里已经落了几个 tick」的计数器。
--
-- 为什么需要它（2026-10-11 生产环境实测发现，**这是个真 bug**）：
--
--   原来的实现用一个**函数内的局部变量** `dirty` 判断「这根 K 线要不要落库」。
--   它在一次 advanceMarket() 调用开始时是 false —— 而生产环境里行情是
--   **每分钟被 cron 推一次、每次正好 60 秒（12 个 tick）**：
--
--     第 1 次调用：从 16:05:12 推到 16:06:00 —— 12 个 tick 全落在 16:05 这根上，
--                 一次边界都没跨过 ⇒ 不落库（对的，因为还没走完）。
--     第 2 次调用：第一个 tick 就跨到 16:06 —— 此时 `dirty` 又刚被重置成 false，
--                 于是 16:05 那根（上一轮辛辛苦苦攒的 12 个 tick）**被当空线丢掉**。
--     第 3 次调用：同样丢掉 16:06 …
--
--   ⇒ 结果是 `game_candles` 一行都不会写，图表上永远只有"正在走的那一根"。
--      而单测没抓到，是因为测试里一次推进 60 个 tick（一次调用跨多根边界），
--      恰好绕开了这个「跨调用」的场景。
--
-- 修法：把「这根 K 线有没有内容」变成**跟着行情行持久化**的计数器，
-- 而不是函数内的临时变量。跨调用累积，跨边界时按它决定是否落库。
--
-- ⚠️ 它是 tick 计数，不是成交笔数：成交量/笔数仍只由玩家下单贡献
--    （见 game_candles.trades 的含义）。两者都会让一根 K 线"有内容"。
ALTER TABLE game_market ADD COLUMN candle_ticks INTEGER NOT NULL DEFAULT 0;
