-- 0057_wb2api_pool_snapshot.sql
-- 给 wb2api_login_sessions 加一列：发起登录那一刻的「网关池 uid 快照」。
--
-- 背景：网关的 login/poll 在登录成功的那一次会**同步**把账号热加载进池
-- （internal/panel/login.go：Pool.Add + Revive），所以等到本站 poll 成功再去查池，
-- 那个账号必然已在池中 —— 分不清「用户带来的新账号」和「本来就在池里的账号」。
--
-- 原来用「poll 时查池，命中即拒绝绑定」来防「绑定池里已有账号白拿权限/邀请奖励」，
-- 结果是：只要 poll 请求因为超时/中途关弹窗而没走完落库，账号就先进了池，
-- 用户重试时反而被自己的账号挡住，永久卡死（ai 权限也拿不到）。
--
-- 改为：start 时拍快照 → poll 成功时用快照判断「登录前是否已在池中」。
--   快照里没有 ⇒ 用户带来的新资源 ⇒ 正常绑定 + 授权限 + 发邀请奖励
--   快照里有   ⇒ 本来就有的账号 ⇒ 仍然绑定 + 授权限（他确实登录了这个账号），
--                但不发邀请奖励（没带来新资源）
--   快照缺失   ⇒ 未知 ⇒ 同上但不发奖励（fail-open 不阻断用户，保守不发奖励）
--
-- 存 uid 数组的 JSON；网关池是几十个账号量级，序列化后 ~1–2 KB，可接受。
ALTER TABLE wb2api_login_sessions ADD COLUMN pool_uids_json TEXT;
