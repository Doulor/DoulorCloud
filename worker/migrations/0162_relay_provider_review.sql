-- 0162_relay_provider_review.sql
--
-- 「中转站入驻」改为**审核制**（2026-10-16 站长要求）。
--
-- 原状（0131）：入驻即生效 —— 登记成功后 enabled 默认 1，任何登录用户立刻能在
-- 「去看看其他中转站」里看到它、点进去读余额。等于「谁都能填一把令牌 + 一个地址，
-- 就把自己的站挂上我们的界面」，站长事前没有一道闸。
--
-- 现在：入驻 → 待审核 → 站长批准后才对**其他用户**可用；站长也可以拒绝并写明理由。
--
-- ---------------------------------------------------------------------------
-- 1) 为什么不复用 enabled，而是新加一列
-- ---------------------------------------------------------------------------
-- enabled 表达的是「站长临时停用」这一个二元态。审核制要表达的是三态
-- （pending / approved / rejected）+ 拒绝理由 + 审核时间/审核人。
-- 硬塞进一个 BOOLEAN 的话，「待审核」与「已拒绝」在库里长得一模一样，用户侧就
-- 没法区分「还在排队」和「被拒了、别等了」—— 而这两句正是站长要求说清楚的话。
--
-- 两列的分工（都在「能不能用」的判据里，见 handlers/relay-providers.ts）：
--   · review_status = 'approved' **且** enabled = 1 ⇒ 才允许被**使用**
--     （读上游余额 / 订阅 / Key / 模型）
--   · 审核通过之后站长仍可临时停用（enabled = 0），不需要把审核态改回去；
--     改回来那天也不必重新审一次
--
-- ---------------------------------------------------------------------------
-- 2) 默认值为什么是 'pending'（fail-closed）
-- ---------------------------------------------------------------------------
-- 将来任何一处 INSERT 忘了写这一列，新站都会是「待审核」而不是「自动生效」。
-- 审核制的默认必须是「不许」—— 默认「许」等于把这道闸废掉，而且废得无声无息
-- （界面上一切正常，只是新站突然都能用了）。
--
-- ---------------------------------------------------------------------------
-- 3) 🔴 存量数据：本迁移执行那一刻库里的每一行都必须变成 approved
-- ---------------------------------------------------------------------------
-- 上面的 DEFAULT 会把**已有行**也写成 pending（SQLite 的 ADD COLUMN 会把默认值
-- 应用到存量行），后果是：
--   · 登记人再也看不到自己登记过的站（列表只返回 approved 或自己的 —— 自己的那台
--     倒是还能看到，但状态是「待审核」，他会以为要重新提交）；
--   · 线上现有 3 条立刻从所有用户的列表里消失，站长还得手工点三次审批。
-- 这是不可接受的回归，所以紧接着**一次性全部回填成 approved**（现有 3 条由此保持
-- 与上线前完全一致的行为）。
--
-- ⚠️ 这条 UPDATE **不带任何条件**，它认的是「跑这一下的时刻」：本文件只允许执行
--    一次（D1 的迁移表会记录）。若有人手工重跑本文件，请先确认库里没有新的 pending 行 ——
--    否则会把待审核的站直接批掉。
--    刻意**不**写成 `WHERE created_at < '某个日期'`：那会把「哪天算存量」变成一个
--    需要人维护的常量，且一旦日期写错，存量行会静默变回待审核（正是本节要避免的回归），
--    而写对了也并不能让重跑变得安全（重跑时新 pending 行的 created_at 只会更晚）。
--
-- reviewed_at 保持 NULL：存量行**没有**审核记录，不编一个假时间出来。
-- 管理端显示「—」，语义就是「审核制之前登记的」。
--
-- ⚠️ 线上 D1 由站长手动执行（本项目从不跑 migrations apply）：
--   npx wrangler d1 execute doulor-mail --remote --config wrangler.toml \
--     --file=./migrations/0162_relay_provider_review.sql

ALTER TABLE relay_providers ADD COLUMN review_status TEXT NOT NULL DEFAULT 'pending';
-- 拒绝理由（展示给登记人）。批准时为 NULL —— 这一列不承载「内部备注」，
-- 免得将来往里写管理员才该看的话、又被用户侧的接口带出去。
ALTER TABLE relay_providers ADD COLUMN review_note TEXT;
ALTER TABLE relay_providers ADD COLUMN reviewed_at TEXT;
ALTER TABLE relay_providers ADD COLUMN reviewed_by TEXT;

-- 存量数据：见上面第 3 节。
UPDATE relay_providers SET review_status = 'approved';

-- 管理端列表要按「待审核优先 + 原有排序」看，用户侧列表要按审核态过滤，
-- 两者都落在同一个索引上（部分索引不适用：查询里既有 review_status 也有 enabled）。
CREATE INDEX IF NOT EXISTS idx_relay_providers_review
  ON relay_providers(review_status, enabled, sort);
