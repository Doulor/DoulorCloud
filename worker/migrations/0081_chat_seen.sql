-- 0081_chat_seen.sql
-- 公共聊天室侧边栏「N 条新消息」角标：按人记已读。
--
-- 背景：聊天室原来只能在社区广场右侧栏点进去，没有任何「有新消息」提示，
-- 不看就等于不知道。现在侧边栏给它一个独立入口 + 角标。
--
-- chat_seen_at：该用户最后一次打开聊天室的时间。
--   角标数 = 我看过之后、别人发的消息数。
--   进入聊天室页面时刷新为当前时间，角标随即归零。
--
-- NULL = 从没打开过（含本次上线前的老用户）→ 回落到「最近 24 小时」口径，
-- 避免一上线就给所有人弹出一个积累很久的大数字。
-- 这与 community_seen_at（迁移 0043）是同一套口径，刻意保持一致。
--
-- ⚠️ 必须**先跑这条迁移再部署代码**：新的 /api/attention 与 /api/chat/unread
--    会无条件读这一列，列不存在会整页 500。
-- ⚠️ D1 一次只执行一条语句，本文件只有一条，但仍请逐条执行（不要用 --file 塞多条）。

ALTER TABLE users ADD COLUMN chat_seen_at TEXT;
