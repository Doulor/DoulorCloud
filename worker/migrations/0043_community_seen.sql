-- 0043_community_seen.sql
-- 社区广场侧边栏「N 条新帖子」角标改为**按人记已读**。
--
-- 原来算的是「最近 24 小时全站新帖数」—— 纯时间窗口，跟「你看没看过」无关，
-- 所以用户点进社区读完之后角标还在，读不掉的数字等于没有信息量。
--
-- community_seen_at：该用户最后一次打开社区广场的时间。
--   角标数 = 我看过之后、别人发的、未删除的帖子数。
--   进入社区页面时把它刷新为当前时间，角标随即归零。
--
-- NULL = 从没打开过（含本次上线前的老用户）→ 回落到旧的「最近 24 小时」口径，
-- 避免一上线就给所有人弹出一个积累了很久的大数字。

ALTER TABLE users ADD COLUMN community_seen_at TEXT;
