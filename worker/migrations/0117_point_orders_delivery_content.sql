-- 0117_point_orders_delivery_content.sql
--
-- 新增一种「统一内容」交付方式（delivery='content'）：发一段**人人相同**的固定内容
-- （网盘链接 / 使用说明 / 通用兑换码），下单即到账，不消耗库存、不需要卡密池。
--
-- 与已有的 `code`（卡密池，一人一条、用完即止）相对：
--   · code    —— 每条不同，靠 point_product_codes 池子支撑
--   · content —— 所有人相同，内容直接写在商品的 delivery_params.content 里
--
-- 为什么订单要单独存一列而不是塞进 note：
--   · `note` 在订单列表里是**一行摘要**（` · {note}`），且被多处代码截断到 300 字；
--     而交付内容最长 2000 字、可能带多行（链接 + 说明），塞进去会把列表撑爆。
--   · 内容是买家**买到的东西**，必须能反复查看（刷新页面、隔几天回来都还在），
--     不能只靠下单时那一条通知消息 —— 消息会被已读/清掉。
--   · 商品事后被编辑或删除时，历史订单要显示**当时发的原文**，所以存订单快照。
--
-- 该列对其它交付方式恒为 NULL，不影响任何既有逻辑。
-- ⚠️ 线上 D1 由站长手动执行（本项目从不跑 migrations apply）。

ALTER TABLE point_orders ADD COLUMN delivery_content TEXT;
